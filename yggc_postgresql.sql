-- Ministries / programs
CREATE TABLE IF NOT EXISTS ministries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    slug VARCHAR(140) NOT NULL UNIQUE,
    summary VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    icon VARCHAR(50) DEFAULT 'seedling',
    display_order SMALLINT DEFAULT 0 CHECK (display_order >= 0),
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Public team profiles (managed from Admin > Team)
CREATE TABLE IF NOT EXISTS team_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    role VARCHAR(120) NOT NULL,
    bio TEXT DEFAULT NULL,
    photo_path VARCHAR(255) NOT NULL,
    display_order SMALLINT NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_team_visibility_order
    ON team_members (is_active, display_order, name);

-- Gallery photos (managed from Admin > Gallery)
CREATE TABLE IF NOT EXISTS gallery_photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caption VARCHAR(160) NOT NULL,
    category VARCHAR(80) NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_gallery_category_created
    ON gallery_photos (category, created_at);

-- Events (admin-managed)
CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    event_date DATE NOT NULL,
    event_time TIME NULL,
    location VARCHAR(200) NOT NULL,
    image VARCHAR(255) DEFAULT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'upcoming'
        CHECK (status IN ('upcoming', 'completed', 'cancelled')),
    created_by INTEGER NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_event_date ON events (event_date);
CREATE INDEX IF NOT EXISTS idx_status ON events (status);

-- Donations
CREATE TABLE IF NOT EXISTS donations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_name VARCHAR(120) NOT NULL,
    donor_email VARCHAR(150) NOT NULL,
    donor_phone VARCHAR(30) DEFAULT NULL,
    amount DECIMAL(12,2) NOT NULL,
    currency VARCHAR(6) NOT NULL DEFAULT 'USD',
    fund VARCHAR(80) NOT NULL DEFAULT 'General Fund',
    frequency VARCHAR(20) NOT NULL DEFAULT 'one_time'
        CHECK (frequency IN ('one_time', 'monthly')),
    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN ('mobile_money', 'card', 'bank_transfer', 'paypal')),
    transaction_ref VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    message VARCHAR(500) DEFAULT NULL,
    is_anonymous BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_donations_status ON donations (status);
CREATE INDEX IF NOT EXISTS idx_created_at ON donations (created_at);
CREATE INDEX IF NOT EXISTS idx_frequency ON donations (frequency);

CREATE TABLE IF NOT EXISTS admin_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL,
    donation_id INTEGER NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_admin_donation_notification UNIQUE (admin_id, donation_id),
    CONSTRAINT fk_notification_admin FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_donation FOREIGN KEY (donation_id) REFERENCES donations(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_admin_unread ON admin_notifications (admin_id, is_read, id);

-- Contact / get-involved messages
CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(30) DEFAULT NULL,
    subject VARCHAR(150) NOT NULL,
    body TEXT NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'contact' CHECK (source IN ('contact', 'volunteer')),
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

